// Developer utility: generate a versioned snapshot from the existing schema.
// Uses an empty in-memory SQLite DB; it never opens the live store.sqlite file.
const {openDatabase}=require('../src/db');
const {writeFileSync}=require('node:fs');
const {join}=require('node:path');
const db=openDatabase(':memory:');
const objects=db.prepare("SELECT type,name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type,name").all();
const tables=objects.filter(row=>row.type==='table');
const foreignKeys=[];
const tableSql=tables.map(row=>row.sql
  .replace(/(\w+) INTEGER((?: NOT NULL| UNIQUE| PRIMARY KEY)*) REFERENCES (\w+)\((\w+)\)/g,(_,column,options,target,key)=>{
    foreignKeys.push(`ALTER TABLE "${row.name}" ADD FOREIGN KEY (${column}) REFERENCES ${target}(${key}) DEFERRABLE INITIALLY DEFERRED`);
    return `${column} INTEGER${options}`;
  })
  .replace(/\bINTEGER\b/g,'BIGINT')
  .replace(/\bBLOB\b/g,'BYTEA')
  .replace(/\bREAL\b/g,'DOUBLE PRECISION')
  .replace(/\((\w+) IS NOT NULL\)/g,'(($1 IS NOT NULL)::integer)')
  .replace(/\bid BIGINT PRIMARY KEY\b/g,'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/COLLATE NOCASE/g,'')
  .replace(/DEFAULT CURRENT_TIMESTAMP/g,"DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))")
  .replace(/REFERENCES (\w+)\((\w+)\)/g,'REFERENCES $1($2) DEFERRABLE INITIALLY DEFERRED')
);
const sql=`-- PostgreSQL schema version 1; domain schema corresponds to SQLite version 8.
-- UTC timestamps stay as fixed-width text to preserve existing snapshots/reports.
${tableSql.join(';\n')};
${foreignKeys.join(';\n')};
${objects.filter(row=>row.type==='index').map(row=>row.sql).join(';\n')};
CREATE UNIQUE INDEX promotions_code_ci_idx ON promotions(lower(code));
CREATE FUNCTION sync_catalog_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME='categories' THEN UPDATE products SET category=NEW.name WHERE category_id=NEW.id;
  ELSE UPDATE products SET brand=NEW.name WHERE brand_id=NEW.id; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER categories_rename AFTER UPDATE OF name ON categories FOR EACH ROW EXECUTE FUNCTION sync_catalog_name();
CREATE TRIGGER brands_rename AFTER UPDATE OF name ON brands FOR EACH ROW EXECUTE FUNCTION sync_catalog_name();
INSERT INTO shipping_policy(id,fee) VALUES(1,0);
CREATE TABLE postgres_migrations(version INTEGER PRIMARY KEY,applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
INSERT INTO postgres_migrations(version) VALUES(1);
`;
writeFileSync(join(__dirname,'../src/postgres-schema.sql'),sql);
db.close();
console.log('Generated src/postgres-schema.sql');
