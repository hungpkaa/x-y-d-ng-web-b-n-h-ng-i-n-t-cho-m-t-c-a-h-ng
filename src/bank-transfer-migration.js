function bankTransferSchema(dialect='sqlite') {
  const integer=dialect==='postgres'?'BIGINT':'INTEGER';
  const id=dialect==='postgres'?'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY';
  return `
CREATE TABLE bank_transfer_orders(
  order_id ${integer} PRIMARY KEY REFERENCES orders(id),
  bank_code TEXT NOT NULL CHECK(length(bank_code)>0),
  account_number TEXT NOT NULL CHECK(length(account_number)>0),
  account_name TEXT NOT NULL CHECK(length(account_name)>0),
  transfer_reference TEXT NOT NULL UNIQUE CHECK(length(transfer_reference)>0),
  amount ${integer} NOT NULL CHECK(amount>0),
  expires_at ${integer} NOT NULL CHECK(expires_at>0),
  qr_payload TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX bank_transfer_expiry_idx ON bank_transfer_orders(expires_at);
CREATE TABLE bank_transfer_receipts(
  id ${id},
  order_id ${integer} NOT NULL REFERENCES bank_transfer_orders(order_id),
  payment_id ${integer} NOT NULL UNIQUE REFERENCES payments(id),
  actor_id ${integer} NOT NULL REFERENCES users(id),
  bank_transaction_id TEXT NOT NULL UNIQUE CHECK(length(bank_transaction_id)>=3),
  amount ${integer} NOT NULL CHECK(amount>0),
  note TEXT NOT NULL CHECK(length(note)>=3 AND length(note)<=300),
  occurred_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX bank_transfer_receipts_order_idx ON bank_transfer_receipts(order_id);
`;
}
module.exports={bankTransferSchema,migrateBankTransfer(db){db.exec(bankTransferSchema());}};
