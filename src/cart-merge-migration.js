function cartMergeSchema(dialect='sqlite') {
  const id=dialect==='postgres'?'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY';
  const integer=dialect==='postgres'?'BIGINT':'INTEGER';
  return `CREATE TABLE cart_merges(id ${id},cart_id ${integer} NOT NULL REFERENCES carts(id),source_key TEXT NOT NULL UNIQUE,source_hash TEXT NOT NULL,pending_json TEXT NOT NULL DEFAULT '{}'); CREATE INDEX cart_merges_cart_idx ON cart_merges(cart_id);`;
}
module.exports={cartMergeSchema,migrateCartMerges(db){db.exec(cartMergeSchema());}};
