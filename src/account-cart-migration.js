function accountCartSchema(dialect = 'sqlite') {
  const id = dialect === 'postgres' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const integer = dialect === 'postgres' ? 'BIGINT' : 'INTEGER';
  return `
    CREATE TABLE carts (
      id ${id}, user_id ${integer} NOT NULL UNIQUE REFERENCES users(id),
      version ${integer} NOT NULL DEFAULT 1 CHECK(version>=1)
    );
    CREATE TABLE cart_items (
      id ${id}, cart_id ${integer} NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
      variant_id ${integer} NOT NULL REFERENCES product_variants(id),
      quantity ${integer} NOT NULL CHECK(quantity BETWEEN 1 AND 99),
      UNIQUE(cart_id,variant_id)
    );
    CREATE INDEX cart_items_variant_idx ON cart_items(variant_id);
  `;
}
function migrateAccountCart(db) { db.exec(accountCartSchema()); }
module.exports = { accountCartSchema, migrateAccountCart };
