const {readFileSync}=require('node:fs');
const {join}=require('node:path');
function migratePostgres(db) {
  db.exec('BEGIN IMMEDIATE');
  try {
    const exists=db.prepare("SELECT to_regclass('postgres_migrations') AS name").get().name;
    if(!exists) {
      const count=db.prepare("SELECT COUNT(*) n FROM information_schema.tables WHERE table_schema=current_schema() AND table_type='BASE TABLE'").get().n;
      if(count) throw new Error('Database/schema PostgreSQL phải trống trước khi khởi tạo.');
      // Native PostgreSQL DDL is sent without placeholder/syntax translation.
      db.query(readFileSync(join(__dirname,'postgres-schema.sql'),'utf8'));
    } else {
      const versions=db.prepare('SELECT version FROM postgres_migrations ORDER BY version').all();
      if(!versions.length||versions.some((row,index)=>row.version!==index+1)||versions.at(-1).version>3) throw new Error('Phiên bản PostgreSQL schema không được hỗ trợ.');
    }
    if(!db.prepare('SELECT version FROM postgres_migrations WHERE version=2').get()) {
      require('./shipments-migration').migrateShipments({exec(sql){db.query(sql
        .replace(/\bINTEGER\b/g,'BIGINT')
        .replace(/\bid BIGINT PRIMARY KEY\b/g,'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        .replace(/DEFAULT CURRENT_TIMESTAMP/g,"DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))")
        .replace(/REFERENCES (\w+)\((\w+)\)/g,'REFERENCES $1($2) DEFERRABLE INITIALLY DEFERRED'));
      }});
      db.prepare('INSERT INTO postgres_migrations(version) VALUES(2)').run();
    }
    if(!db.prepare('SELECT version FROM postgres_migrations WHERE version=3').get()) {
      require('./engagement-migration').migrateEngagement({exec(sql){db.query(sql
        .replace(/\bINTEGER\b/g,'BIGINT')
        .replace(/\bid BIGINT PRIMARY KEY\b/g,'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        .replace(/DEFAULT CURRENT_TIMESTAMP/g,"DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))")
        .replace(/REFERENCES (\w+)\((\w+)\)/g,'REFERENCES $1($2) DEFERRABLE INITIALLY DEFERRED'));
      }});
      db.prepare('INSERT INTO postgres_migrations(version) VALUES(3)').run();
    }
    db.exec('COMMIT');
    db.ids=new Set(db.prepare("SELECT table_name FROM information_schema.columns WHERE table_schema=current_schema() AND column_name='id'").all().map(row=>row.table_name));
  } catch(error) {db.exec('ROLLBACK');throw error;}
}
module.exports={migratePostgres};
